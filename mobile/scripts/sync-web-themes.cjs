// Copies the web design system's theme colours, radii and status colours into the app:
//   node mobile/scripts/sync-web-themes.cjs   (from the repository root)
// Run it whenever frontend/src/styles/themes.css or the status colours in globals.css change.
const fs = require("fs");
const themes = fs.readFileSync("frontend/src/styles/themes.css", "utf8");
const globals = fs.readFileSync("frontend/src/app/globals.css", "utf8");
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const block = (css, sel) => {
  const i = css.indexOf(sel + " {");
  if (i < 0) throw new Error(`Missing ${sel}`);
  return css.slice(i, css.indexOf("}", i));
};
const vars = (b) => Object.fromEntries([...b.matchAll(/--([a-z0-9_-]+):\s*([^;]+);/g)].map((m) => [camel(m[1]), m[2].trim()]));
const px = (v) => parseFloat(v);

const out = { themes: {}, status: {} };
for (const t of ["hazard", "control-room", "setu", "ledger-slate"]) {
  const base = vars(block(themes, `[data-theme="${t}"]`));
  const colours = (sel) => Object.fromEntries(Object.entries(vars(block(themes, sel))).filter(([k]) => !k.startsWith("shadow")));
  out.themes[t] = {
    radius: { xs: px(base.radiusXs), sm: px(base.radiusSm), md: px(base.radiusMd), lg: px(base.radiusLg), xl: px(base.radiusXl) },
    borderWidth: px(base.borderW),
    light: colours(`[data-theme="${t}"]:not(.dark)`),
    dark: colours(`.dark[data-theme="${t}"]`),
  };
}
// Status and "needs you" action colours (globals.css :root and .dark); keys keep the web's names.
for (const [mode, sel] of [["light", ":root"], ["dark", ".dark"]]) {
  const raw = [...block(globals, sel).matchAll(/--(st|act)-([a-z_]+):\s*([^;]+);/g)];
  out.status[mode] = {
    ink: raw.find((m) => m[1] === "st" && m[2] === "ink")[3].trim(),
    permit: Object.fromEntries(raw.filter((m) => m[1] === "st" && m[2] !== "ink").map((m) => [m[2], m[3].trim()])),
    action: Object.fromEntries(raw.filter((m) => m[1] === "act").map((m) => [m[2], m[3].trim()])),
  };
}
fs.writeFileSync(
  "mobile/src/theme/web-themes.ts",
  `// Generated by mobile/scripts/sync-web-themes.cjs from the web design system. Do not edit by hand.\nexport const WEB_THEMES = ${JSON.stringify(out.themes, null, 2)} as const;\n\nexport const WEB_STATUS = ${JSON.stringify(out.status, null, 2)} as const;\n`,
);
console.log("Wrote mobile/src/theme/web-themes.ts");
